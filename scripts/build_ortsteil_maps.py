"""Generate one zoomed local map image per BORIS Ortsteil/PLZ filter option.

The wizard must work from file:// without live tile requests. This script
downloads the tiles once at development time, crops them to the BRW extent of
each Ortsteil/PLZ group and writes a manifest with the EPSG:25832 bounds so
app.js can register the BRW dots on the matching image.

Run with: py scripts\\build_ortsteil_maps.py
Attribution: (c) OpenStreetMap contributors, ODbL (shown in the UI).
"""

import io
import json
import math
import os
import urllib.request

from PIL import Image

from build_map_background import UA, mercator, utm32n_to_wgs84

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA_FILE = os.path.join(ROOT, "data", "boris-ratingen.js")
OUT_DIR = os.path.join(ROOT, "assets", "maps")
MANIFEST = os.path.join(ROOT, "data", "boris-maps.js")

VIEW_W, VIEW_H = 1080, 630
TILE = 256


def fetch_tile(zoom, tx, ty):
    url = f"https://tile.openstreetmap.de/{zoom}/{tx}/{ty}.png"
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return Image.open(io.BytesIO(resp.read())).convert("RGB")


def bounds_for(zones):
    """Extent of one Ortsteil/PLZ group, padded and matched to the SVG aspect."""
    xs = [float(z["x"]) for z in zones]
    ys = [float(z["y"]) for z in zones]
    cx, cy = (min(xs) + max(xs)) / 2.0, (min(ys) + max(ys)) / 2.0
    width = max(max(xs) - min(xs), 700.0)
    height = max(max(ys) - min(ys), 700.0)
    min_x, max_x = cx - width * 0.72, cx + width * 0.72
    min_y, max_y = cy - height * 0.72, cy + height * 0.72
    height = max_y - min_y
    width = height * VIEW_W / VIEW_H
    min_x, max_x = cx - width / 2.0, cx + width / 2.0
    return min_x, max_x, min_y, max_y


def choose_zoom(min_x, max_x, min_y, max_y):
    west, north = utm32n_to_wgs84(min_x, max_y)
    east, south = utm32n_to_wgs84(max_x, min_y)
    lat = math.radians((north + south) / 2.0)
    metres_per_pixel_at_z0 = 156543.03392 * math.cos(lat)
    # A wider extent needs a LOWER zoom so the whole area fits in VIEW_W pixels.
    zoom = round(math.log2(VIEW_W * metres_per_pixel_at_z0 / (max_x - min_x)))
    return max(12, min(17, zoom)), west, east, north, south


def build_image(bounds, out_path):
    min_x, max_x, min_y, max_y = bounds
    zoom, west, east, north, south = choose_zoom(*bounds)
    left_x, top_y = mercator(west, north)
    right_x, bottom_y = mercator(east, south)
    scale = 2.0**zoom
    tx0, ty0 = left_x * scale, top_y * scale
    tx1, ty1 = right_x * scale, bottom_y * scale
    x0, x1 = math.floor(tx0), math.floor(tx1)
    y0, y1 = math.floor(ty0), math.floor(ty1)

    canvas = Image.new("RGB", ((x1 - x0 + 1) * TILE, (y1 - y0 + 1) * TILE), "white")
    for ty in range(y0, y1 + 1):
        for tx in range(x0, x1 + 1):
            canvas.paste(fetch_tile(zoom, tx, ty), ((tx - x0) * TILE, (ty - y0) * TILE))

    crop = (
        round((tx0 - x0) * TILE),
        round((ty0 - y0) * TILE),
        round((tx1 - x0) * TILE),
        round((ty1 - y0) * TILE),
    )
    image = canvas.crop(crop).resize((VIEW_W, VIEW_H), Image.LANCZOS)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    image.save(out_path, "PNG", optimize=True)
    return zoom


def main():
    with open(DATA_FILE, encoding="utf-8") as handle:
        text = handle.read()
    data = json.loads(text[text.index("{"):text.rindex("}") + 1])

    groups = {}
    for zone in data["zones"]:
        name = zone.get("ortsteil") or zone.get("gemarkung") or ""
        key = name + (" · " + zone["plz"] if zone.get("plz") else "")
        groups.setdefault(key, []).append(zone)

    manifest = {}
    for index, key in enumerate(sorted(groups)):
        bounds = bounds_for(groups[key])
        relative = f"assets/maps/zone-{index:02d}.png"
        zoom = build_image(bounds, os.path.join(ROOT, relative))
        manifest[key] = {
            "file": relative,
            "minX": bounds[0], "maxX": bounds[1],
            "minY": bounds[2], "maxY": bounds[3],
            "zoom": zoom,
        }
        print(f"{relative}  z{zoom}  {key}  ({len(groups[key])} zones)")

    with open(MANIFEST, "w", encoding="utf-8") as handle:
        handle.write("/* Generated by scripts/build_ortsteil_maps.py. Do not edit manually. */\n")
        handle.write("window.VW_BORIS_MAPS = ")
        json.dump(manifest, handle, ensure_ascii=False, indent=2)
        handle.write(";\n")
    print(f"Wrote {MANIFEST} ({len(manifest)} Ortsteil maps)")


if __name__ == "__main__":
    main()
